"""Статистика по сменам (08:00–08:00) и шуточные подъёбки к ней.

Отдельный файл специально, чтобы не захламлять bot.py — вся логика смен,
шуток и форматирования живёт здесь, bot.py только дёргает render_shift_stats().
"""

import random
from datetime import datetime, timedelta

SHIFT_START_HOUR = 8


def current_shift_bounds(now: datetime) -> tuple[datetime, datetime]:
    """Возвращает (начало, конец) смены, в которую попадает now.
    Смена идёт с 08:00 до 08:00 следующего дня.
    """
    shift_start = now.replace(hour=SHIFT_START_HOUR, minute=0, second=0, microsecond=0)
    if now.hour < SHIFT_START_HOUR:
        shift_start -= timedelta(days=1)
    return shift_start, shift_start + timedelta(days=1)


def previous_shift_bounds(now: datetime) -> tuple[datetime, datetime]:
    """Границы ТОЛЬКО ЧТО завершившейся смены — для автоотчёта, который
    стреляет ровно в 08:00: в этот момент current_shift_bounds(now) уже
    вернула бы НОВУЮ, только начавшуюся смену, а нужна предыдущая.
    """
    return current_shift_bounds(now - timedelta(minutes=1))


