def _joke_for(count: int, previous: str | None = None) -> str:
    """Шутка всегда из одного и того же пула, независимо от count — число
    используется только для подстановки в шаблон. Если известна previous
    (готовая, со вчера, шутка этого же человека), по возможности её не
    повторяет — сравнение идёт по шаблону, а не по итоговому тексту с
    числом внутри.
    """
    choices = JOKES
    if previous is not None:
        narrowed = [t for t in JOKES if t.format(n=count) != previous]
        if narrowed:  # если пул из одного варианта — не сужаем до пустого, иначе нечего выбрать
            choices = narrowed

    template = random.choice(choices)
    return template.format(n=count)


def render_shift_stats(
    rows, shift_start: datetime, shift_end: datetime, is_current: bool,
    previous_jokes: dict | None = None,
) -> tuple[str, dict]:
    """rows — записи из db.get_shift_log() (с полями username, baggage_status).
    Считаем только 'received' как реально принятый багаж — 'missing' в
    зачёт смены не идёт, это не рейс, а "рейс потеряли", так себе достижение.

    previous_jokes — {username: вчерашняя_шутка_этого_человека}, чтобы не
    повторять её сегодня. Возвращает (текст_отчёта, {username: сегодняшняя
    шутка}) — второе нужно сохранить вызывающей стороне для следующего раза.
    """
    previous_jokes = previous_jokes or {}
    counts: dict[str, int] = {}
    for row in rows:
        if row["baggage_status"] != "received":
            continue
        name = row["username"] or "без имени"
        counts[name] = counts.get(name, 0) + 1

    period = f"{shift_start.strftime('%d.%m %H:%M')}–{shift_end.strftime('%d.%m %H:%M')}"
    header = f"📊 <b>Статистика смены</b> ({period}){' — ещё идёт' if is_current else ''}\n"

    if not counts:
        return header + "\nЗа смену никто ничего не принял. Немая сцена.", {}

    lines = [header]
    today_jokes: dict[str, str] = {}
    for name, count in sorted(counts.items(), key=lambda x: -x[1]):
        joke = _joke_for(count, previous_jokes.get(name))
        today_jokes[name] = joke
        lines.append(f"{name} — {joke}")

    return "\n".join(lines), today_jokes
